import java.io.IOException;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.ArrayList;
import java.util.List;
import java.util.Set;
import java.util.stream.Stream;

import static java.nio.charset.StandardCharsets.UTF_8;

/*

Joins every study guide, in reading order, into FULL-CONTEXT.md with a table of contents at the top.
Run it after changing any guide (JDK 17+, no build needed):

    java docs/understanding/build-full-context.java          from the repo root
    java build-full-context.java                             from docs/understanding
    java build-full-context.java <guides directory>

Order: the top-level NN*.md files by name (05 < 05a < 05b), with 07-modules/ inserted after 06 in MODULE_ORDER
(any module file not listed there follows, alphabetically). AI-TUTOR-PROMPT.md and FULL-CONTEXT.md are not
included. Output: UTF-8, LF line endings. Keep this file ASCII: the java launcher reads a source file in the
platform charset (windows-1252 on the dev machine), so a literal non-ASCII character would come out garbled.

 */
public class BuildFullContext {

    static final String OUTPUT = "FULL-CONTEXT.md";
    static final String DASH = String.valueOf((char) 0x2014);      // em dash, without a non-ASCII source character
    static final Set<String> EXCLUDED = Set.of(OUTPUT, "AI-TUTOR-PROMPT.md");
    static final List<String> MODULE_ORDER = List.of("domain-and-commands.md", "book.md", "engine.md", "journal.md",
            "exchange-and-replay.md", "ledger-and-snapshots.md", "exchange-service.md", "gateway.md", "client-and-main.md");

    record Guide(Path file, String relative, String title, String text, int words) {
    }

    public static void main(String[] args) throws IOException {
        Path dir = locate(args);
        List<Guide> guides = new ArrayList<>();
        for (Path file : ordered(dir)) {
            String text = Files.readString(file, UTF_8).replace("\r\n", "\n");
            String relative = dir.relativize(file).toString().replace('\\', '/');
            guides.add(new Guide(file, relative, title(text, relative), text, words(text)));
        }
        if (guides.isEmpty()) {
            throw new IllegalStateException("No guides found in " + dir);
        }

        int total = guides.stream().mapToInt(Guide::words).sum();
        StringBuilder out = new StringBuilder();
        out.append("# ExchangeServer2 " + DASH + " Study guides (full context)\n\n")
                .append("> Generated by `build-full-context.java` from ").append(guides.size())
                .append(" guides (about ").append(total).append(" words). Do not edit by hand: edit the guides, then run\n")
                .append("> `java docs/understanding/build-full-context.java` from the repo root.\n\n")
                .append("## Table of contents\n\n");
        for (Guide g : guides) {
            out.append("- [").append(g.title()).append("](#").append(anchor(g.relative())).append(") " + DASH + " `")
                    .append(g.relative()).append("` (").append(g.words()).append(" words)\n");
        }
        for (Guide g : guides) {
            out.append("\n\n---\n\n<a id=\"").append(anchor(g.relative())).append("\"></a>\n\n")
                    .append("<!-- source: docs/understanding/").append(g.relative()).append(" -->\n\n")
                    .append(g.text().strip()).append('\n');
        }

        Path target = dir.resolve(OUTPUT);
        Files.writeString(target, out.toString(), UTF_8);
        System.out.println("Wrote " + target + ": " + guides.size() + " guides, about " + total + " words");
    }

    static Path locate(String[] args) {
        if (args.length > 0) {
            return Path.of(args[0]);
        }
        Path fromRoot = Path.of("docs", "understanding");
        if (Files.isDirectory(fromRoot)) {
            return fromRoot;
        }
        if (Files.exists(Path.of("00-START-HERE.md"))) {
            return Path.of(".");
        }
        throw new IllegalStateException("Run from the repo root or from docs/understanding, or pass the directory");
    }

    static List<Path> ordered(Path dir) throws IOException {
        List<Path> topLevel;
        try (Stream<Path> s = Files.list(dir)) {
            topLevel = s.filter(p -> Files.isRegularFile(p) && p.getFileName().toString().matches("\\d\\d.*\\.md"))
                    .filter(p -> !EXCLUDED.contains(p.getFileName().toString()))
                    .sorted()
                    .toList();
        }
        List<Path> modules = modules(dir.resolve("07-modules"));

        List<Path> result = new ArrayList<>();
        boolean modulesPlaced = false;
        for (Path p : topLevel) {
            if (!modulesPlaced && p.getFileName().toString().compareTo("07") >= 0) {
                result.addAll(modules);
                modulesPlaced = true;
            }
            result.add(p);
        }
        if (!modulesPlaced) {
            result.addAll(modules);
        }
        return result;
    }

    static List<Path> modules(Path dir) throws IOException {
        if (!Files.isDirectory(dir)) {
            return List.of();
        }
        List<Path> all;
        try (Stream<Path> s = Files.list(dir)) {
            all = s.filter(p -> p.getFileName().toString().endsWith(".md")).sorted().toList();
        }
        List<Path> result = new ArrayList<>();
        for (String name : MODULE_ORDER) {
            Path p = dir.resolve(name);
            if (all.contains(p)) {
                result.add(p);
            }
        }
        for (Path p : all) {
            if (!result.contains(p)) {
                result.add(p);
            }
        }
        return result;
    }

    static String title(String text, String fallback) {
        for (String line : text.split("\n")) {
            if (line.startsWith("# ")) {
                return line.substring(2).strip();
            }
        }
        return fallback;
    }

    static int words(String text) {
        String trimmed = text.strip();
        return trimmed.isEmpty() ? 0 : trimmed.split("\\s+").length;
    }

    static String anchor(String relative) {
        return "guide-" + relative.replaceAll("\\.md$", "").replaceAll("[^A-Za-z0-9]+", "-").toLowerCase();
    }
}
